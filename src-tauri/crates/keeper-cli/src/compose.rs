//! keeper-cli's composition (story 123.2, MA/AD-2): the explicit list of
//! modules this binary hosts — `app` and `graph` — built by keeper-runtime,
//! whose start check runs every time the binary starts. Every graph verb is
//! reached through the local dispatcher this hands out, by operation id.

use std::sync::Arc;

use keeper_app_api::DomainVm;
use keeper_graph::module::{DomainBinding, GraphConfig, GraphModule};
use keeper_runtime::{AppInfo, LocalDispatcher, Runtime, StartError};
use keeper_runtime_api::Module;
use sha2::{Digest as _, Sha256};

/// The one committed catalogue snapshot, embedded at build (SR-20).
const SNAPSHOT: &[u8] = include_bytes!("../../../../catalogue/snapshot.json");

/// SHA-256 (hex) of `bytes`.
pub fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// The modules this binary lists, in order.
fn modules(config: GraphConfig, domains: Vec<DomainBinding>) -> Vec<Arc<dyn Module>> {
    vec![
        keeper_runtime::app_module(),
        Arc::new(GraphModule::new(config, domains)),
    ]
}

/// Build the runtime over this binary's list: `domains` are the replicas
/// the command line opened, one per `--database`.
pub fn build(
    config: GraphConfig,
    domains: Vec<DomainBinding>,
) -> Result<(Runtime, LocalDispatcher), StartError> {
    let info = AppInfo {
        version: env!("CARGO_PKG_VERSION").to_owned(),
        build: option_env!("KEEPER_BUILD_SHA").unwrap_or("dev").to_owned(),
        snapshot_digest: sha256_hex(SNAPSHOT),
        domains: domains
            .iter()
            .map(|d| DomainVm {
                server: d.server.clone(),
                domain: d.database.clone(),
            })
            .collect(),
    };
    Runtime::build(info, modules(config, domains))
}

#[cfg(test)]
mod tests {
    use super::*;
    use keeper_runtime_api::{Effect, ErrorCode, OpError};
    use serde_json::{json, Value};
    use std::path::{Path, PathBuf};

    fn repo_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
    }

    /// The real list with one domain whose replica could not be opened:
    /// the composition needs no server to start.
    fn composed() -> (Runtime, LocalDispatcher) {
        let config = GraphConfig {
            state: std::env::temp_dir().join(format!("keeper-cli-compose-{}", std::process::id())),
            worker: None,
            macos_evidence: false,
            worker_sha256: None,
            ledger: None,
        };
        let domains = vec![DomainBinding {
            server: "https://hq.example".into(),
            database: "work".into(),
            actor: "ana".into(),
            client: "dev1".into(),
            source: Err(OpError::new(
                ErrorCode::Refused,
                "unauthorised",
                "KEEPER_GRAPH_TOKEN is required",
            )),
        }];
        build(config, domains).expect("keeper-cli's own list starts")
    }

    fn block_on<F: std::future::Future>(future: F) -> F::Output {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("runtime")
            .block_on(future)
    }

    /// The snapshot, as the catalogue of this build writes it (CR-5, CR-6).
    fn snapshot(runtime: &Runtime) -> String {
        let root = repo_root();
        let digest = |path: &str| {
            let bytes = std::fs::read(root.join(path))
                .unwrap_or_else(|e| panic!("vectors file {path}: {e}"));
            sha256_hex(&bytes)
        };
        let operations: Vec<Value> = runtime
            .catalogue()
            .into_iter()
            .map(|spec| keeper_runtime_api::snapshot_entry(spec, &digest))
            .collect();
        let document = json!({
            "about": "Generated by keeper-cli's test `the_snapshot_is_the_catalogue` (story 123.2). \
                      Regenerate with KEEPER_WRITE_CATALOGUE=1; checked by scripts/check-catalogue.py.",
            "operations": operations,
        });
        let mut text = serde_json::to_string_pretty(&document).expect("json");
        text.push('\n');
        text
    }

    /// Each composition root builds its real list under its targets' cfgs
    /// (this binary: Linux and macOS).
    #[test]
    fn the_real_list_starts() {
        let (runtime, _) = composed();
        let modules = runtime.modules();
        assert_eq!(
            modules,
            vec![
                ("app".to_owned(), keeper_app_api::ModuleState::Ready),
                ("graph".to_owned(), keeper_app_api::ModuleState::Ready),
            ]
        );
    }

    /// AC1: through the dispatcher, `app.modules` lists `app` and `graph`
    /// ready; the catalogue holds the 5 `app` and 18 `graph` operations with
    /// every field; the four `decide` operations are `decide`; the snapshot
    /// carries the epic's wire rules.
    #[test]
    fn the_dispatcher_answers_the_catalogue() {
        let (runtime, dispatcher) = composed();
        let modules = block_on(dispatcher.call("app.modules", json!({}))).expect("app.modules");
        assert_eq!(
            modules,
            json!({"modules": [{"id": "app", "state": "ready"}, {"id": "graph", "state": "ready"}]})
        );
        let version = block_on(dispatcher.call("app.version", json!({}))).expect("app.version");
        let on_disk = std::fs::read(repo_root().join("catalogue/snapshot.json")).expect("snapshot");
        assert_eq!(version["snapshot_digest"], json!(sha256_hex(&on_disk)));
        let domains = block_on(dispatcher.call("app.domains", json!({}))).expect("app.domains");
        assert_eq!(
            domains,
            json!({"domains": [{"server": "https://hq.example", "domain": "work"}]})
        );
        assert_eq!(dispatcher.dispatches(), 3);

        let catalogue = runtime.catalogue();
        let ids: Vec<&str> = catalogue.iter().map(|s| s.id).collect();
        let app: Vec<&str> = ids
            .iter()
            .copied()
            .filter(|i| i.starts_with("app."))
            .collect();
        let graph: Vec<&str> = ids
            .iter()
            .copied()
            .filter(|i| i.starts_with("graph."))
            .collect();
        assert_eq!(
            app,
            [
                "app.capabilities",
                "app.domains",
                "app.health",
                "app.modules",
                "app.version"
            ]
        );
        assert_eq!(graph.len(), 18, "{graph:?}");
        assert_eq!(ids.len(), 23);
        for spec in &catalogue {
            assert!(!spec.summary.is_empty(), "{}: summary", spec.id);
            assert!(
                (spec.input)().as_value().is_object(),
                "{}: input schema",
                spec.id
            );
            assert!(
                (spec.output)().as_value().is_object(),
                "{}: output schema",
                spec.id
            );
            assert!(!spec.cli.words.is_empty(), "{}: cli", spec.id);
            match spec.module() {
                "app" => assert_eq!(spec.scope, keeper_runtime_api::Scope::App),
                _ => assert_eq!(spec.scope, keeper_runtime_api::Scope::Domain("/target")),
            }
        }
        let mut decide: Vec<&str> = catalogue
            .iter()
            .filter(|s| s.effect == Effect::Decide)
            .map(|s| s.id)
            .collect();
        decide.sort_unstable();
        assert_eq!(
            decide,
            [
                "graph.acknowledge",
                "graph.decide",
                "graph.discard",
                "graph.reverse"
            ]
        );

        let snapshot: Value = serde_json::from_str(&snapshot(&runtime)).expect("snapshot json");
        let entry = |id: &str| {
            snapshot["operations"]
                .as_array()
                .and_then(|ops| ops.iter().find(|op| op["id"] == id))
                .cloned()
                .unwrap_or_else(|| panic!("{id} in the snapshot"))
        };
        let apply = entry("graph.apply");
        assert_eq!(apply["effect"], "write");
        assert_eq!(apply["proposal"], json!({"via": "graph.propose"}));
        assert_eq!(
            apply["wire_forbid"],
            json!(["/approval_id", "/event_time_ms"])
        );
        assert_eq!(apply["to_proposal"], true);
        assert_eq!(apply["wire_gate"], true);
        let propose = entry("graph.propose");
        assert_eq!(propose["proposal"], "itself");
        assert_eq!(
            propose["wire_forbid"],
            json!([
                "/reviewers",
                "/base_revision",
                "/expires_at_ms",
                "/proposal_id",
                "/change/approval_id",
                "/change/event_time_ms"
            ])
        );
        assert_eq!(
            propose["wire_fix"],
            json!([
                {"pointer": "/reviewers", "fixed": "device_actor"},
                {"pointer": "/base_revision", "fixed": "null"},
                {"pointer": "/expires_at_ms", "fixed": {"expires_in_ms": 604_800_000_u64}},
                {"pointer": "/proposal_id", "fixed": "fresh_ulid"},
            ])
        );
        assert_eq!(propose["wire_gate"], true);
        let enqueue = entry("graph.enqueue");
        assert_eq!(enqueue["proposal"], "none");
        assert_eq!(enqueue["wire_forbid"], apply["wire_forbid"]);
        assert_eq!(enqueue["wire_gate"], true);
        for id in ["graph.resume", "graph.sync"] {
            let op = entry(id);
            assert_eq!(op["effect"], "write", "{id}");
            assert_eq!(op["wire_forbid"], json!([]), "{id}");
            assert_eq!(op["wire_gate"], false, "{id}");
        }
        for id in [
            "graph.decide",
            "graph.acknowledge",
            "graph.reverse",
            "graph.discard",
        ] {
            let op = entry(id);
            assert_eq!(op["effect"], "decide", "{id}");
            assert_eq!(op["wire_forbid"], json!([]), "{id}");
        }
        assert_eq!(
            entry("graph.inspect")["input_enums"]["/entity"],
            json!(["node", "edge", "content"])
        );
    }

    /// `catalogue/snapshot.json` is this build's catalogue, byte for byte
    /// (pinned like `docs/settings-keys.md`). `KEEPER_WRITE_CATALOGUE=1`
    /// rewrites it.
    #[test]
    fn the_snapshot_is_the_catalogue() {
        let (runtime, _) = composed();
        let generated = snapshot(&runtime);
        let path = repo_root().join("catalogue/snapshot.json");
        if std::env::var_os("KEEPER_WRITE_CATALOGUE").is_some() {
            std::fs::write(&path, &generated).expect("write the snapshot");
        }
        let committed = std::fs::read_to_string(&path).expect("catalogue/snapshot.json");
        assert!(
            committed == generated,
            "catalogue/snapshot.json is stale: rerun this test with KEEPER_WRITE_CATALOGUE=1"
        );
    }
}
