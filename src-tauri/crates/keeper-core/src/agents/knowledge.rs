    /// stamped note as an agent's and unreviewed — `okf_facts` names its
    /// agent generator and no reviewer, and the label wrapper's fact is
    /// `human_reviewed: false`, which keeps a read of it at `agent`
    /// integrity. After a person's tick both say a person reviewed it.
    #[test]
    fn keeper_reads_a_harvested_note_as_unreviewed() {
        let types = types();
        let stored = stamp(CANDIDATE, &harvest(&types)).expect("stored").text;
        let facts = okf_facts(&stored).expect("frontmatter");
        assert_eq!(
            facts.generated_by.as_deref(),
            Some("agent:tola-grey@electra")
        );
        assert_eq!(facts.generated_actor, Some(ActorKind::Agent));
        assert_eq!(facts.verified_by, None);
        assert!(!facts.human_reviewed);
        assert_eq!(okf_label_facts(&stored).human_reviewed, Some(false));

        let ticked = review(&stored, "tgorka", AT, true);
        let facts = okf_facts(&ticked).expect("frontmatter");
        assert!(facts.human_reviewed);
        assert_eq!(facts.verified_by.as_deref(), Some("human:tgorka"));
        assert_eq!(facts.verified_actor, Some(ActorKind::Person));
        assert_eq!(okf_label_facts(&ticked).human_reviewed, Some(true));
    }

    /// 95.5 acceptance 1, the pure half: whatever the model wrote in
