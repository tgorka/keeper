    /// R95K-16: ticking a copy whose review is in the legacy spelling —
    /// `verified: true` beside `verified_by`, here with CRLF line ends and a
    /// comment — keeps that review and writes it canonical: one `verified`
    /// block, no `verified_by`, `human_reviewed: true`, the comment and the
