    #[test]
    fn a_legacy_review_is_written_canonical() {
        let legacy = "---\r\ntype: Note\r\ntitle: Taxes\r\n# kept: a comment\r\nverified: true\r\nverified_by: human:tgorka\r\nhuman_reviewed: false\r\n---\r\n\r\nBody.\r\n";
        let ticked = review(legacy, "tgorka", AT, true);
        let (fm, _) = Frontmatter::parse(&ticked);
        let doc = okf::read(&fm);
        assert_eq!(
            doc.verified,
            [Verification {
                by: "human:tgorka".to_owned(),
                at: None
            }]
        );
        assert_eq!(doc.verified_shape, okf::VerifiedShape::Canonical);
        assert_eq!(fm.count("verified_by"), 0);
        assert_eq!(fm.as_bool(HUMAN_REVIEWED), Some(true));
        assert!(ticked.contains("# kept: a comment\r\n"), "{ticked:?}");
        assert!(ticked.ends_with("---\r\n\r\nBody.\r\n"), "{ticked:?}");
        assert!(!ticked.replace("\r\n", "").contains('\n'), "{ticked:?}");

        let two = "---\ntype: Note\nverified: true\nverified_by: [human:marta, human:tgorka]\nhuman_reviewed: true\n---\n\nBody.\n";
        let unticked = review(two, "tgorka", AT, false);
        let (fm, _) = Frontmatter::parse(&unticked);
        let doc = okf::read(&fm);
        assert_eq!(
            doc.verified
                .iter()
                .map(|v| v.by.as_str())
                .collect::<Vec<_>>(),
            ["human:marta"]
        );
        assert_eq!(doc.verified_shape, okf::VerifiedShape::Canonical);
        assert_eq!(fm.count("verified_by"), 0);
        assert_eq!(fm.as_bool(HUMAN_REVIEWED), Some(true));
    }

    /// R95K2-09: a review written as one map — a flow map, or `by:` and
    /// `at:` indented under `verified:` with no `-` — is read, and ticking
    /// it as the same person rewrites it as the one block list a writer
    /// leaves, reviewer and time kept, every other byte as it was.
    #[test]
    fn a_single_map_review_is_written_as_a_list() {
        let list = "verified:\n  - by: human:tgorka\n    at: 2026-10-01T08:00:00Z\n";
        for single in [
            "verified: {by: human:tgorka, at: 2026-10-01T08:00:00Z}\n",
            "verified:\n  by: human:tgorka\n  at: 2026-10-01T08:00:00Z\n",
        ] {
            let note = |verified: &str| {
                format!(
                    "---\ntype: Note\ntitle: Taxes\n{verified}human_reviewed: true\n---\n\nBody.\n"
                )
            };
            assert_eq!(
                review(&note(single), "tgorka", AT, true),
                note(list),
                "{single}"
            );
        }
    }

    /// R95K2-05: a source's author is read as YAML reads it, escapes and
    /// all: `"\u0068uman:tgorka"` and `"\x75ser:marta"` name a person to any
    /// YAML reader, so they are refused as one; an escape YAML does not
    /// define is a source keeper cannot read for certain, refused as such.
    #[test]
    fn an_escaped_author_is_read_as_yaml_reads_it() {
        let types = types();
        let harvest = harvest(&types);
        let with = |author: &str| {
            CANDIDATE.replace(
                "    title: The answer\n",
                &format!("    author: {author}\n"),
            )
        };
        for (author, actor) in [
            ("\"\\u0068uman:tgorka\"", "human:tgorka"),
            ("\"\\x75ser:marta\"", "user:marta"),
            ("\"\\U00000068uman:tgorka\"", "human:tgorka"),
        ] {
            assert_eq!(
                stamp(&with(author), &harvest),
                Err(KnowledgeRefusal::ClaimsPerson {
                    actor: actor.to_owned()
                }),
                "{author}"
            );
        }
        for unreadable in ["\"\\qhuman:tgorka\"", "\"human:\"tgorka\""] {
            assert!(
                matches!(
                    stamp(&with(unreadable), &harvest),
                    Err(KnowledgeRefusal::SourcesUnreadable { .. })
                ),
                "{unreadable}"
            );
        }
        let tool = stamp(&with("\"agent:tola\\u002dgrey@electra\""), &harvest).expect("stored");
        assert!(tool
            .text
            .contains("author: \"agent:tola\\u002dgrey@electra\""));
    }

    /// 95.5 acceptance 7 (Q17): a person's tick appends their canonical
    /// `verified` entry and sets `human_reviewed: true`, leaving every
    /// other byte, and keeper's OKF reader reads it back; the untick takes
    /// exactly that entry out again and sets `false`; another person's
    /// review survives both, and a second tick changes nothing.
    #[test]
    fn only_a_person_marks_a_note_reviewed() {
        let types = types();
        let stored = stamp(CANDIDATE, &harvest(&types)).expect("stored").text;

        let ticked = review(&stored, "tgorka", AT, true);
        let doc = okf::read(&Frontmatter::parse(&ticked).0);
        assert_eq!(
            doc.verified,
            [Verification {
                by: "human:tgorka".to_owned(),
                at: Some(AT.to_owned())
            }]
        );
        assert_eq!(doc.verified_shape, okf::VerifiedShape::Canonical);
        assert_eq!(
            Frontmatter::parse(&ticked).0.as_bool(HUMAN_REVIEWED),
            Some(true)
        );
        let expected = stored
            .replace(
                "  at: 2026-10-06T09:00:00Z\nhuman_reviewed: false\n",
                "  at: 2026-10-06T09:00:00Z\nverified:\n  - by: human:tgorka\n    at: 2026-10-06T09:00:00Z\nhuman_reviewed: true\n",
            );
        assert_eq!(ticked, expected, "every other byte stays");
        assert_eq!(review(&ticked, "tgorka", "2027-01-01", true), ticked);

        let unticked = review(&ticked, "tgorka", AT, false);
        assert_eq!(unticked, stored, "the untick restores the bytes");

        let by_marta = review(&ticked, "marta", AT, true);
        let without_tgorka = review(&by_marta, "tgorka", AT, false);
        let doc = okf::read(&Frontmatter::parse(&without_tgorka).0);
        assert_eq!(
            doc.verified
                .iter()
                .map(|v| v.by.as_str())
                .collect::<Vec<_>>(),
            ["human:marta"]
        );
        assert_eq!(
            Frontmatter::parse(&without_tgorka)
                .0
                .as_bool(HUMAN_REVIEWED),
            Some(true)
        );
    }
